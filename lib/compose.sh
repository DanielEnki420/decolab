# shellcheck shell=bash
# shellcheck disable=SC2154 # decolab_root, SECRETS_DIR, ...: lib/common.sh
# lib/compose.sh - the ONE way Decolab runs docker compose
#
# Every stack needs the same three env files (Immich a fourth); a stack started without them
# gets empty variables (no password, wrong user) and still starts. So
# nothing runs "docker compose" by hand: install.sh and update.sh use
# decolab_compose. (Not "dc": that is a calculator in /usr/bin, and timeout
# cannot run a shell function - it would have run the calculator.)
#
#   decolab_stacks            stacks of this installation, in start order
#   decolab_compose STACK ARGS...   docker compose for STACK (core, immich, ...);
#                                   COMPOSE_TIMEOUT_S limits how long it may take
#   compose_wait_healthy WAIT SETTLE STEP NAME...   until healthy (see below)

# decolab_stacks - core first, Uptime Kuma last: it joins the other stacks'
# networks. Watchtower only where it was installed.
decolab_stacks() {
  echo core
  is_yes MODULE_IMMICH && echo immich
  is_yes MODULE_VAULTWARDEN && echo vaultwarden
  docker inspect watchtower >/dev/null 2>&1 && echo watchtower
  is_yes MODULE_UPTIME_KUMA && echo uptime-kuma
  return 0
}

# compose_env_files [STACK] - the env files, in order (later ones win).
# Immich's compose file interpolates its database login (${DB_PASSWORD} ...),
# so immich.env is one of them for that stack.
compose_env_files() {
  printf '%s\n' "$DECOLAB_CONF" "$SECRETS_DIR/runtime.env" "$SECRETS_DIR/compose-secrets.env"
  [ "${1:-}" != immich ] || printf '%s\n' "$SECRETS_DIR/immich.env"
}

decolab_compose() {
  local stack=$1 f
  shift
  local args=(compose --project-directory "$decolab_root")
  while read -r f; do args+=(--env-file "$f"); done < <(compose_env_files "$stack")
  if [ "$stack" = core ]; then
    args+=(-f "$decolab_root/compose/core.yml")
  else
    args+=(-f "$decolab_root/stacks/$stack/compose.yml")
  fi
  # Kuma's networks of the enabled modules, generated by install.sh.
  if [ "$stack" = uptime-kuma ] && [ -s "$DECOLAB_STATE_DIR/compose.networks.yml" ]; then
    args+=(-f "$DECOLAB_STATE_DIR/compose.networks.yml")
  fi
  if [ -n "${COMPOSE_TIMEOUT_S:-}" ]; then
    timeout "$COMPOSE_TIMEOUT_S" docker "${args[@]}" "$@"
  else
    docker "${args[@]}" "$@"
  fi
}

# compose_wait_healthy WAIT_S SETTLE_S STEP_S NAME... - waits for each
# container: healthy where the image has a healthcheck, else running and not
# restarting for SETTLE_S seconds. Prints " name(state health)" for every
# container that did not get there within WAIT_S; prints nothing if all did.
compose_wait_healthy() {
  local wait=$1 settle=$2 step=$3 name i ok restarts since st
  shift 3
  for name in "$@"; do
    i=0 ok=0 restarts="" since=0
    while [ "$i" -lt "$wait" ]; do
      st=$(docker inspect -f '{{.State.Status}} {{if .State.Health}}{{.State.Health.Status}}{{else}}none{{end}} {{.RestartCount}}' "$name" 2>/dev/null)
      # shellcheck disable=SC2086 # three words, split on purpose
      set -- $st
      if [ "${1:-}" = running ] && [ "${2:-}" = healthy ]; then ok=1 && break; fi
      if [ "${1:-}" = running ] && [ "${2:-}" = none ]; then
        [ -n "$restarts" ] || restarts=${3:-0} since=$i
        [ "${3:-0}" = "$restarts" ] || restarts=${3:-0} since=$i
        [ $((i - since)) -lt "$settle" ] || { ok=1 && break; }
      fi
      sleep "$step"
      i=$((i + step))
    done
    [ "$ok" = 1 ] || printf ' %s(%s %s)' "$name" "${1:-gone}" "${2:-}"
  done
  return 0
}
